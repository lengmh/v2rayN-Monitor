import { addDays } from './ranges.ts';
import type { Bucket, Range } from './ranges.ts';
export interface ChartPoint { label: string; upload: string; download: string; recoveredUpload?: string; recoveredDownload?: string }
export interface ChartSlot { label: string; point?: ChartPoint }
function hourKey(date: Date, timeZone: string): string {
  const parts = Object.fromEntries(new Intl.DateTimeFormat('en-CA', { timeZone, year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', second: '2-digit', hourCycle: 'h23' }).formatToParts(date).map(p => [p.type, p.value]));
  const local = Date.UTC(Number(parts.year), Number(parts.month) - 1, Number(parts.day), Number(parts.hour), Number(parts.minute), Number(parts.second));
  const offset = Math.round((local - date.getTime()) / 60_000), absolute = Math.abs(offset);
  return `${parts.year}-${parts.month}-${parts.day}T${parts.hour}:00${offset >= 0 ? '+' : '-'}${String(Math.floor(absolute / 60)).padStart(2, '0')}:${String(absolute % 60).padStart(2, '0')}`;
}
/** Undefined means the chosen granularity is too dense for an honest, readable chart. */
export function chartSlots(points: ChartPoint[], range: Range, bucket: Bucket, timeZone: string, limit = 1600): ChartSlot[] | undefined {
  const keys: string[] = [];
  if (bucket === 'hour') {
    for (let at = Date.parse(range.start); at < Date.parse(range.end); at += 3600_000) {
      const key = hourKey(new Date(at), timeZone);
      if (!keys.includes(key)) keys.push(key);
      if (keys.length > limit) return undefined;
    }
  } else {
    let date = range.from;
    if (bucket === 'week') { const weekday = new Date(`${date}T12:00:00Z`).getUTCDay(); date = addDays(date, -((weekday + 6) % 7)); }
    if (bucket === 'month') date = `${date.slice(0, 7)}-01`;
    if (bucket === 'year') date = `${date.slice(0, 4)}-01-01`;
    while (date <= range.through) {
      keys.push(bucket === 'month' ? date.slice(0, 7) : bucket === 'year' ? date.slice(0, 4) : date);
      if (keys.length > limit) return undefined;
      if (bucket === 'day' || bucket === 'week') date = addDays(date, bucket === 'day' ? 1 : 7);
      else { const value = new Date(`${date}T12:00:00Z`); if (bucket === 'month') value.setUTCMonth(value.getUTCMonth() + 1); else value.setUTCFullYear(value.getUTCFullYear() + 1); date = value.toISOString().slice(0, 10); }
    }
  }
  const byLabel = new Map(points.map(point => [point.label, point]));
  // Keep any backend bucket not generated by an unusual timezone transition; never silently drop measured data.
  for (const point of points) if (!keys.includes(point.label)) keys.push(point.label);
  if (keys.length > limit) return undefined;
  return keys.sort(bucket === 'hour' ? (a, b) => Date.parse(a) - Date.parse(b) : undefined).map(label => ({ label, point: byLabel.get(label) }));
}
export function shortLabel(label: string, bucket: Bucket): string {
  if (bucket === 'hour') return label.slice(11, 16);
  if (bucket === 'day' || bucket === 'week') return label.slice(5);
  return label;
}
